// Writes docs/import/: a JSON Schema for character files, a valid example character, and every content id,
// so an existing sheet can be converted (by hand or by an LLM) into a file the app's "Import JSON" accepts.
// Usage: npm run import-kit
import fs from "node:fs";
import { z } from "zod";
import type { Entry, EntryType, PackMeta } from "../content/schema/index.ts";
import { Registry } from "../src/content/registry.ts";
import { finishBuild } from "../src/rules/builder.ts";
import { CharacterDoc, newCharacter } from "../src/rules/character.ts";
import { applyLevelUp } from "../src/rules/levelup.ts";
import { bundledPacks } from "./validate-packs.ts";

const OUT = "docs/import";
const packs = bundledPacks();
const reg = new Registry(packs.flatMap((p) => p.entries as Entry[]), packs.map((p) => p.meta as PackMeta));

// ---- schema ----
fs.mkdirSync(OUT, { recursive: true });
const schema = z.toJSONSchema(CharacterDoc, { target: "draft-2020-12", io: "input", reused: "ref" });
fs.writeFileSync(`${OUT}/character.schema.json`, JSON.stringify({ title: "DaggerPlayer character", ...schema }, null, 2) + "\n");

// ---- example: a level 2 Ranger, built with the real rules so it is valid ----
let n = 0;
const fakeUuid = () => `00000000-0000-4000-8000-${String(++n).padStart(12, "0")}`;
const realUuid = crypto.randomUUID.bind(crypto);
crypto.randomUUID = fakeUuid as typeof crypto.randomUUID; // stable ids in the example
let c = newCharacter(["srd"]);
c.identity = { name: "Wren Ashdown", pronouns: "she/her", description: "Tall, weathered, carries a bone-handled knife." };
Object.assign(c.build, {
  classId: "srd/class/ranger",
  subclassId: "srd/subclass/wayfinder",
  ancestry: { kind: "single", id: "srd/ancestry/elf" },
  communityId: "srd/community/wildborne",
  traits: { agility: 2, strength: 1, finesse: 1, instinct: 0, presence: 0, knowledge: -1 },
  gear: { primaryId: "srd/weapon/shortbow", secondaryId: null, armorId: "srd/armor/leather-armor", potion: "health", classItem: "A trophy from your first kill", spellItem: "", extraItems: "Whetstone" },
  domainCardIds: ["srd/domain-card/gifted-tracker", "srd/domain-card/vicious-entangle"],
  classNotes: "",
});
c.build.experiences[0].name = "Tracker";
c.build.experiences[1].name = "Survivalist";
const cls = reg.get("srd/class/ranger", "class")!;
c.build.background = cls.backgroundQuestions.map((q, i) => ({ question: q, answer: i === 0 ? "My first kill was the beast that took my brother." : "" }));
c.build.connections = cls.connectionQuestions.map((q) => ({ question: q, answer: "" }));
c = finishBuild(c, reg, new Date("2026-11-06T12:00:00Z"));
c = applyLevelUp(
  c,
  {
    level: 2,
    newExperience: { id: fakeUuid(), name: "Mountain Guide", bonus: 2 },
    advancements: [{ optionId: "hp" }, { optionId: "traits", traits: ["agility", "instinct"] }],
    domainCardId: "srd/domain-card/natures-tongue",
    exchange: null,
  },
  reg,
);
c.state.hpMarked = 2;
c.state.stressMarked = 1;
c.state.hope = 3;
c.notes.session = "Owe Kaz a favor.";
crypto.randomUUID = realUuid;
CharacterDoc.parse(c);
fs.writeFileSync(`${OUT}/character-template.json`, JSON.stringify(c, null, 2) + "\n");

// ---- ids ----
const SECTIONS: [EntryType, string, (e: Entry) => string][] = [
  ["class", "Classes", (e) => (e.type === "class" ? `class items: ${e.classItems.map((x) => `"${x}"`).join(" or ")}` : "")],
  ["subclass", "Subclasses", (e) => (e.type === "subclass" ? `class: ${e.classId}` : "")],
  ["ancestry", "Ancestries", (e) => (e.type === "ancestry" ? `top: ${e.features[0].name}; bottom: ${e.features[1].name}` : "")],
  ["community", "Communities", () => ""],
  ["transformation", "Transformations", () => ""],
  ["domain-card", "Domain cards", (e) => (e.type === "domain-card" ? `${e.domainId.split("/").pop()} level ${e.level}` : "")],
  ["weapon", "Weapons", (e) => (e.type === "weapon" ? `tier ${e.tier} ${e.category}${e.burden === 2 ? ", two-handed" : ""}` : "")],
  ["armor", "Armor", (e) => (e.type === "armor" ? `tier ${e.tier}` : "")],
  ["consumable", "Consumables", () => ""],
  ["item", "Items", () => ""],
  ["beastform", "Beastforms", (e) => (e.type === "beastform" ? `tier ${e.tier}` : "")],
];
const lines = [
  "# Content ids",
  "",
  "Every id a character file can reference. Generated by `npm run import-kit`; don't edit by hand.",
  "",
  "Slug rule: lower-case the name, drop apostrophes, `&` → `and`, any other run of non-letters/digits → `-`. Example: `Nature’s Tongue` → `srd/domain-card/natures-tongue`.",
  "",
];
for (const [type, title, note] of SECTIONS) {
  lines.push(`## ${title}`, "", "| id | name | notes |", "| --- | --- | --- |");
  for (const e of reg.all(type)) lines.push(`| \`${e.id}\` | ${e.name} | ${note(e)} |`);
  lines.push("");
}
const p = reg.get("srd/progression/leveling", "progression")!;
lines.push(
  "## Level-up advancement option ids",
  "",
  "| optionId | extra fields | slots per tier (2/3/4) | cost |",
  "| --- | --- | --- | --- |",
  ...p.advancements.map((a) => {
    const extra: Record<string, string> = { traits: "`traits`: two trait names", experiences: "`experienceIds`: two experience ids", "domain-card": "`cardId`", subclass: "`subclassId`: your subclass id", multiclass: "`classId`, `domainId`, `subclassId`" };
    return `| \`${a.id}\` | ${extra[a.id] ?? ""} | ${["2", "3", "4"].map((t) => a.slotsByTier[t as "2"] ?? "—").join(" / ")} | ${a.cost} |`;
  }),
  "",
);
fs.writeFileSync(`${OUT}/ids.md`, lines.join("\n"));
console.log(`Wrote ${OUT}/character.schema.json, character-template.json, ids.md`);
